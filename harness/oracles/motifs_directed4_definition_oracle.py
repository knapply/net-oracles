def edge_set(text):
    return frozenset(tuple(map(int, e.split(">"))) for e in text.split(",")) if text != "-" else frozenset()


def canonical(edges):
    """The least sorted edge tuple over all relabelings of the 4 nodes."""
    return min(tuple(sorted((p[a], p[b]) for a, b in edges)) for p in permutations(range(4)))


def weakly_connected(edges):
    reach = {0}
    grew = True
    while grew:
        grew = False
        for a, b in edges:
            if (a in reach) != (b in reach):
                reach |= {a, b}
                grew = True
    return len(reach) == 4


CLASSES = [canonical(edge_set(t)) for t in ISOCLASS4]
assert len(set(CLASSES)) == 218
INDEX = {c: i for i, c in enumerate(CLASSES)}
CONNECTED = [i for i, t in enumerate(ISOCLASS4) if weakly_connected(edge_set(t))]
assert len(CONNECTED) == 199


def census(fx):
    arcs = {(a, b) for a, b in zip(fx.src, fx.tgt) if a != b}
    counts = [0] * 218
    memo = {}
    for nodes in combinations(range(fx.n), 4):
        local = frozenset((i, j) for i, a in enumerate(nodes) for j, b in enumerate(nodes)
                          if i != j and (a, b) in arcs)
        if not weakly_connected(local):
            continue
        key = local
        if key not in memo:
            memo[key] = INDEX[canonical(local)]
        counts[memo[key]] += 1
    return [counts[i] for i in CONNECTED]


def main() -> None:
    spec = load_area(AREA)
    count = 0
    for name in fixture_names():
        fx = load_fixture(name)
        for variant, v in spec.items():
            if ORACLE not in v["oracles"] or not applies(v, fx):
                continue
            write_values(ORACLE, name, variant, census(fx))
            count += 1
    write_version(ORACLE, DEFINITION_VERSION)
    print(f"definition ({AREA}): wrote {count} golden files")


if __name__ == "__main__":
    main()
